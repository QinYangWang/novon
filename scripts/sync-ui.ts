#!/usr/bin/env bun
/**
 * Pulls the component library into src/ui, src/components and src/styles.
 * Those files are installed, never edited by hand: run this to update them.
 *
 *   bun scripts/sync-ui.ts            # reinstall every item, regenerate accents.css
 *   bun scripts/sync-ui.ts --accents  # only regenerate accents.css
 */
import { $ } from 'bun'
import { writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const REGISTRY = 'https://qinyangwang.github.io/ui/r'
const root = join(import.meta.dir, '..')

export const items = [
  'theme', 'typeset', 'icons', 'button', 'badge', 'card', 'alert', 'tabs', 'accordion', 'tooltip',
  'menu', 'file-tree', 'marquee', 'scroll-progress', 'theme-toggle', 'command-palette', 'breadcrumb',
  'avatar', 'icon-chip', 'scroll-area', 'segmented-control', 'drawer',
]
const accents = ['blue', 'neutral', 'green', 'orange', 'rose', 'violet']

type Vars = Record<string, string>
const block = (selector: string, vars: Vars) =>
  `${selector} {\n${Object.entries(vars).map(([k, v]) => `  --${k}: ${v};`).join('\n')}\n}`

async function writeAccents() {
  const out = ['/* Generated by scripts/sync-ui.ts from the accent presets. Do not edit. */']
  for (const name of accents) {
    const res = await fetch(`${REGISTRY}/theme-${name}.json`)
    if (!res.ok) throw new Error(`theme-${name}: ${res.status}`)
    const item = (await res.json()) as { cssVars?: { light?: Vars; dark?: Vars } }
    if (item.cssVars?.light) out.push(block(`html[data-accent="${name}"]`, item.cssVars.light))
    if (item.cssVars?.dark) out.push(block(`html[data-accent="${name}"].dark`, item.cssVars.dark))
  }
  await writeFile(join(root, 'src/styles/accents.css'), `${out.join('\n\n')}\n`)
}

if (!process.argv.includes('--accents')) {
  await $`bunx --bun shadcn@latest add -y -o ${items.map((i) => `@qinyang/${i}`)}`.cwd(root)
}
await writeAccents()
console.log('ui synced')
